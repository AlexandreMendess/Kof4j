package dev.kof.compiler;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

/**
 * The RS error-correction faces of the QR file reader
 * ({@code libs/qrcode/QrDecode.kd} — correction of up to floor(ecc/2) byte
 * errors per block via syndromes, Berlekamp-Massey, Chien and Forney):
 * (a) symbols with k isolated damaged modules (k within the block's
 * correction capacity for every version used) decode back to the exact text;
 * (b) damage beyond every block's capacity is refused with the named
 * {@code QRCODE:} diagnostic instead of decoding garbage. The damaged
 * fixtures are generated by the Python qrcode module (an independent
 * implementation) and the checks skip named when Python/PIL is absent.
 */
class QrCodeDamageCorrectionTest implements LibraryInstallSupport {

    private final CompilerDriver driver = new CompilerDriver();

    @Override
    public String libraryName() {
        return "qrcode";
    }

    @Override
    public List<String> libraryMarkers() {
        return List.of("QrDecode.kf");
    }

    @Override
    public List<String> libraryNames() {
        return List.of("qrcode", "image");
    }

    private static final List<String> DAMAGE_TEXTS = List.of(
            "Hello damage 1", "Hello damage 3", "Hello damage 5",
            "https://example.com/damage", "test data 42!");
    private static final int[] DAMAGE_COUNTS = {1, 3, 5, 5, 4};

    @TempDir
    Path tmp;

    @Test
    void isolatedDamageIsCorrectedAndDecoded() throws Exception {
        assumeTrue(pythonHasQrcodeAndPil(),
                "python qrcode module + PIL absent — damage correction check skipped");
        Path root = tmp.resolve("damage");
        Files.createDirectories(root);
        Path dir = root.resolve("pngs");
        Files.createDirectories(dir);
        // generate valid PNGs and flip k isolated data modules (within the
        // block's correction capacity floor(ecc/2) for every version used)
        String script = String.join("\n", List.of(
                "import sys, random",
                "import qrcode",
                "from qrcode.util import QRData",
                "from qrcode import constants, util",
                "from PIL import Image",
                "random.seed(11)",
                "texts = sys.argv[1].split('|')",
                "dmg = [int(x) for x in sys.argv[2].split(',')]",
                "out = sys.argv[3]",
                "for i, text in enumerate(texts):",
                "    q = qrcode.QRCode(error_correction=constants.ERROR_CORRECT_M, border=4)",
                "    q.add_data(QRData(text, mode=util.MODE_8BIT_BYTE))",
                "    q.make()",
                "    m = q.get_matrix()",
                "    n = len(m)",
                "    img = Image.new('L', (n, n), 255)",
                "    for r in range(n):",
                "        for c in range(n):",
                "            if m[r][c]:",
                "                img.putpixel((c, r), 0)",
                "    # exclude every function pattern (finders+separators, timing,",
                "    # format strips, dark module, alignments, version info): the",
                "    # layout lives on the symbol grid, which sits at offset 4",
                "    align = {1: [], 2: [18], 3: [22], 4: [26], 5: [30], 6: [34],",
                "             7: [22, 38], 8: [24, 42], 9: [26, 46], 10: [28, 50]}",
                "    s = n - 8",
                "    version = (s - 17) // 4",
                "    reserved = set()",
                "    for (r0, c0) in [(0, 0), (0, s - 8), (s - 8, 0)]:",
                "        for r in range(r0, r0 + 8):",
                "            for c in range(c0, c0 + 8):",
                "                if 0 <= r < s and 0 <= c < s:",
                "                    reserved.add((r, c))",
                "    centers = [6] + align[version]",
                "    for a in centers:",
                "        for b2 in centers:",
                "            if (a, b2) not in reserved:",
                "                for r in range(a - 2, a + 3):",
                "                    for c in range(b2 - 2, b2 + 3):",
                "                        if 0 <= r < s and 0 <= c < s:",
                "                            reserved.add((r, c))",
                "    for ti in range(8, s - 8):",
                "        reserved.add((6, ti))",
                "        reserved.add((ti, 6))",
                "    for f in range(15):",
                "        if f < 6: rr = f",
                "        elif f < 8: rr = f + 1",
                "        else: rr = s - 15 + f",
                "        reserved.add((rr, 8))",
                "        if f < 8: cc = s - 1 - f",
                "        elif f < 9: cc = 15 - f",
                "        else: cc = 14 - f",
                "        reserved.add((8, cc))",
                "    reserved.add((s - 8, 8))",
                "    if version >= 7:",
                "        for v in range(18):",
                "            reserved.add((v // 3, v % 3 + s - 11))",
                "            reserved.add((v % 3 + s - 11, v // 3))",
                "    data_cells = [(r, c) for r in range(4, n - 4) for c in range(4, n - 4)",
                "                  if (r - 4, c - 4) not in reserved]",
                "    for k in range(dmg[i]):",
                "        r, c = random.choice(data_cells)",
                "        img.putpixel((c, r), 255 if img.getpixel((c, r)) == 0 else 0)",
                "    img.save(out + '/d' + str(i) + '.png')"));
        Path py = root.resolve("damage.py");
        Files.writeString(py, script);
        StringBuilder textsArg = new StringBuilder();
        StringBuilder dmgArg = new StringBuilder();
        for (int i = 0; i < DAMAGE_TEXTS.size(); i++) {
            if (i > 0) { textsArg.append('|'); dmgArg.append(','); }
            textsArg.append(DAMAGE_TEXTS.get(i));
            dmgArg.append(DAMAGE_COUNTS[i]);
        }
        Process p = new ProcessBuilder("python3", py.toString(), textsArg.toString(),
                dmgArg.toString(), dir.toString())
                .redirectErrorStream(true).start();
        String genOutput = new String(p.getInputStream().readAllBytes(), java.nio.charset.StandardCharsets.UTF_8);
        assertEquals(0, p.waitFor(), "python damage generator: " + genOutput);

        // one Kof program decodes all damaged PNGs
        StringBuilder b = new StringBuilder("import qrcode.QrDecode\n\nmain() {\n");
        for (int i = 0; i < DAMAGE_TEXTS.size(); i++) {
            b.append("    println(decodeQr(\"").append(dir).append("/d").append(i).append(".png\"))\n");
        }
        b.append("}\n");
        Path source = root.resolve("Main.kf");
        Files.writeString(source, b.toString());
        KofInterpreter.Result result = withLibrary(root,
                () -> driver.interpret(List.of(source), root, new String[0]));
        assertEquals(0, result.exitCode(), "damaged symbols must decode: " + result.stderr());
        List<String> decoded = List.of(result.stdout().strip().split("\n", -1));
        for (int i = 0; i < DAMAGE_TEXTS.size(); i++) {
            assertEquals(DAMAGE_TEXTS.get(i), decoded.get(i), "damaged symbol " + i);
        }
    }

    @Test
    void overCapacityDamageIsRefusedByParityCheck() throws Exception {
        assumeTrue(pythonHasQrcodeAndPil(), "python PIL absent — corruption check skipped");
        Path root = tmp.resolve("corrupt");
        Files.createDirectories(root);
        Path dir = root.resolve("pngs");
        Files.createDirectories(dir);
        // generate a valid PNG, then wipe a large contiguous data area: the
        // damage exceeds every block's correction capacity, so the reader
        // must refuse by name instead of decoding garbage
        List<String> script = List.of(
                "import sys",
                "import qrcode",
                "from qrcode.util import QRData",
                "from qrcode import constants, util",
                "from PIL import Image",
                "q = qrcode.QRCode(error_correction=constants.ERROR_CORRECT_M, border=4)",
                "q.add_data(QRData('Hello corruption', mode=util.MODE_8BIT_BYTE))",
                "q.make()",
                "m = q.get_matrix()",
                "n = len(m)",
                "img = Image.new('L', (n, n), 255)",
                "for r in range(n):",
                "    for c in range(n):",
                "        if m[r][c]:",
                "            img.putpixel((c, r), 0)",
                "# wipe a large data-area patch: whitening a module flips the",
                "# underlying bits, and 12x12 modules exceed the capacity of",
                "# every block of this symbol",
                "for r in range(12, 24):",
                "    for c in range(12, 24):",
                "        if (r, c) != (21, 8) and not (r <= 8 and c <= 8) and r != 6 and c != 6:",
                "            img.putpixel((c, r), 255)",
                "img.save(sys.argv[1])");
        Path py = root.resolve("corrupt.py");
        Files.writeString(py, String.join("\n", script));
        Path png = dir.resolve("corrupt.png");
        Process p = new ProcessBuilder("python3", py.toString(), png.toString())
                .redirectErrorStream(true).start();
        String genOutput = new String(p.getInputStream().readAllBytes(), java.nio.charset.StandardCharsets.UTF_8);
        assertEquals(0, p.waitFor(), "python corruptor: " + genOutput);

        String program = "import qrcode.QrDecode\n\nmain() {\n    println(decodeQr(\""
                + png.toString() + "\"))\n}\n";
        Path source = root.resolve("Main.kf");
        Files.writeString(source, program);
        KofInterpreter.Result result = withLibrary(root,
                () -> driver.interpret(List.of(source), root, new String[0]));
        assertTrue(result.exitCode() != 0, "over-capacity damage must fail");
        assertTrue(result.stderr().contains("QRCODE"),
                "the refusal must be named: " + result.stderr());
    }

    private boolean pythonHasQrcodeAndPil() {
        try {
            Process p = new ProcessBuilder("python3", "-c", "import qrcode, PIL")
                    .redirectErrorStream(true).start();
            return p.waitFor() == 0;
        } catch (Exception e) {
            return false;
        }
    }

    private <T> T withLibrary(Path root, CheckedSupplier<T> action) throws Exception {
        copyLibrary(root.resolve("kof-install/lib/kof-libs"));
        String previous = System.getProperty("kof.install.dir");
        System.setProperty("kof.install.dir", root.resolve("kof-install").toString());
        try {
            return action.get();
        } finally {
            if (previous == null) System.clearProperty("kof.install.dir");
            else System.setProperty("kof.install.dir", previous);
        }
    }

    @FunctionalInterface
    private interface CheckedSupplier<T> {
        T get() throws Exception;
    }
}
