package dev.kof.compiler.nat;

import dev.kof.compiler.IRClass;
import dev.kof.compiler.IRLocalVariable;
import dev.kof.compiler.IRMethod;
import dev.kof.compiler.KofDebugInfo;
import dev.kof.compiler.Type;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * §687: a Kof frame past ~2 KiB made the riscv64 build die in the ASSEMBLER —
 * the §625 slot-zeroing loop emitted {@code sd zero,-2056(s11)} and riscv's
 * {@code ld}/{@code sd} carry a 12-bit SIGNED immediate (±2048), so GNU as
 * rejected every slot past the limit ("illegal operands"). The frame pointer
 * model puts local {@code idx} at {@code -(idx+1)*8-16(s11)}, so ~255 locals
 * cross it — a legitimate program (the AVIF CFL probe's 64x64 luma buffer plus
 * its per-size arrays) could not be built for riscv64 at all.
 *
 * <p>The fix materialises the slot address in {@code t6} past the limit
 * ({@code li t6, |off|} + {@code sub t6, s11, t6}) and stores at offset 0. This
 * asserts the emitted text directly, so it is deterministic and toolchain-free
 * (no as/ld/qemu); RED-first: with the raw offset the {@code (s11)} assertion
 * fails on {@code -2424}.
 *
 * <p>The aarch64 face is asserted too because it is generated by TRANSLATING
 * this same riscv text — the new sequence must be consumed by the translator,
 * not passed through verbatim.
 */
class RiscvLargeFrameAsmTest {

    /** Qualquer acesso de memória com base s11 — o que vira imediato no as. */
    private static final Pattern S11_MEM =
            Pattern.compile("^\\s*(?:ld|sd|lw|sw|lbu|lb|lh|lhu|sb|sh)\\s+\\S+,\\s*(-?\\d+)\\(s11\\)\\s*$");

    private static final int LOCALS = 300;

    private static IRMethod largeFrameMethod() {
        List<IRLocalVariable> locals = new ArrayList<>();
        locals.add(new IRLocalVariable(0, "this", Type.PrimitiveType.INT));
        for (int i = 1; i <= LOCALS; i++) {
            locals.add(new IRLocalVariable(i, "v" + i, Type.PrimitiveType.INT));
        }
        return new IRMethod("big", Type.PrimitiveType.VOID, List.of(), 0,
                List.of(), List.of(), locals, KofDebugInfo.EMPTY, List.of(), List.of());
    }

    private static String riscvAsm() {
        IRMethod method = largeFrameMethod();
        IRClass clazz = new IRClass("Main", "Object", List.of(), 0, List.of(), List.of(method),
                List.of(), null, 0, List.of());
        NativeBackend nb = new NativeBackend();
        nb.allClassesMap.put(clazz.name(), clazz);
        StringBuilder sb = new StringBuilder();
        new NativeRiscvCrossEmit(nb).emitCrossMethodRiscv(sb, clazz, method, false);
        return sb.toString();
    }

    @Test
    void riscvLargeFrameStaysInsideTheTwelveBitImmediate() {
        String asm = riscvAsm();
        int direct = 0;
        int materialized = 0;
        for (String line : asm.split("\n", -1)) {
            if (line.trim().equals("sd zero, 0(t6)")) materialized++;
            Matcher m = S11_MEM.matcher(line);
            if (!m.matches()) continue;
            int off = Integer.parseInt(m.group(1));
            direct++;
            assertTrue(off >= -2048 && off <= 2047,
                    "§687: offset " + off + " não cabe no imediato de 12 bits do ld/sd "
                            + "— o assembler riscv recusa esta linha:\n" + line);
        }
        int slots = LOCALS + 1; // `this` + os LOCALS
        assertTrue(direct + materialized == slots,
                "§687: " + slots + " slots no frame, mas vi " + direct + " escrita(s) direta(s) + "
                        + materialized + " materializada(s):\n" + asm);
    }

    @Test
    void riscvLargeFrameMaterializesTheSlotAddressPastTheLimit() {
        String asm = riscvAsm();
        int lastOff = -NativeRiscvCrossFrame.localOff(LOCALS);
        assertTrue(asm.contains("li t6, " + lastOff + "\n"),
                "§687: o slot " + LOCALS + " (offset -" + lastOff + ") precisa materializar o endereço "
                        + "em t6:\n" + asm);
        assertTrue(asm.contains("sub t6, s11, t6\n"),
                "§687: o endereço materializado usa sub (o li leva o valor POSITIVO):\n" + asm);
        // small frames keep the direct form — the guard must not tax them
        IRMethod small = new IRMethod("small", Type.PrimitiveType.VOID, List.of(), 0,
                List.of(), List.of(),
                List.of(new IRLocalVariable(0, "this", Type.PrimitiveType.INT),
                        new IRLocalVariable(1, "x", Type.PrimitiveType.INT)),
                KofDebugInfo.EMPTY, List.of(), List.of());
        IRClass clazz = new IRClass("Main", "Object", List.of(), 0, List.of(), List.of(small),
                List.of(), null, 0, List.of());
        NativeBackend nb = new NativeBackend();
        nb.allClassesMap.put(clazz.name(), clazz);
        StringBuilder sb = new StringBuilder();
        new NativeRiscvCrossEmit(nb).emitCrossMethodRiscv(sb, clazz, small, false);
        assertFalse(sb.toString().contains("li t6,"),
                "§687: frame pequeno não passa pelo t6 (regressão de forma):\n" + sb);
    }

    @Test
    void riscvLargeFrameStillZeroesEveryNonArgSlot() {
        // §625 continua valendo com o guard novo: o slot ou é escrito direto
        // (offset em faixa) ou pelo endereço materializado.
        String asm = riscvAsm();
        for (IRLocalVariable lv : largeFrameMethod().localVariables()) {
            int off = NativeRiscvCrossFrame.localOff(lv.index());
            if (lv.name().equals("this")) {
                // slot 0 recebe o `this` do a0 (não é zerado) — §625 é sobre os
                // slots que NÃO são arg de entrada
                assertTrue(asm.contains("sd a0, " + off + "(s11)\n"),
                        "§625: `this` não salvo do a0 (offset " + off + ")");
            } else if (off >= -2048) {
                assertTrue(asm.contains("sd zero, " + off + "(s11)\n"),
                        "§625: slot " + lv.index() + " não zerado direto (offset " + off + ")");
            } else {
                assertTrue(asm.contains("li t6, " + (-off) + "\n"),
                        "§687: slot " + lv.index() + " não materializa o endereço (offset " + off + ")");
                assertTrue(asm.contains("sd zero, 0(t6)\n"),
                        "§625: slot " + lv.index() + " não é zerado após materializar");
            }
        }
    }

    @Test
    void aarch64TranslationConsumesTheMaterializedAddress() {
        List<String> translated = new ArrayList<>();
        for (String line : riscvAsm().split("\n", -1)) {
            translated.addAll(NativeAarch64Translator.translateRiscvToAarch64(line));
        }
        String aarch = String.join("\n", translated);
        assertFalse(aarch.contains("li t6"),
                "§687: o tradutor aarch64 não pode repassar o `li t6` verbatim:\n" + aarch);
        assertFalse(aarch.contains("sub t6, s11, t6"),
                "§687: o tradutor aarch64 não pode repassar o `sub` verbatim:\n" + aarch);
        for (String line : aarch.split("\n", -1)) {
            Matcher m = Pattern.compile("\\[(x29|sp),\\s*#(-?\\d+)\\]").matcher(line);
            if (!m.find()) continue;
            int off = Integer.parseInt(m.group(2));
            assertTrue(off >= -256 && off <= 255,
                    "§687: aarch64 materializou mal o offset " + off + ": " + line);
        }
    }
}
